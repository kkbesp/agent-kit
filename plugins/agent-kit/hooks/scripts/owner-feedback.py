#!/usr/bin/env python3
"""UserPromptSubmit: замечание владельца превращает в обязательный разбор, а не в извинение.

Разбор реальных сессий: сотни раздражённых замечаний, многие — повтор уже названного
правила («опять», «я же говорил», «каждый раз одно и то же»). Текстовое правило в AGENTS.md
к середине сессии тонет; этот хук напоминает в момент замечания.
Самопроверка: python3 owner-feedback.py --self-test
"""
import json, os, re, sys

COMPLAINT = re.compile(
    r"опять|снова|почему|зачем|не работает|не то\b|сломал|туп|идиот|долбо|хуй|хуе|хрен|пизд|бля|"
    r"ерунд|я же (говорил|просил|сказал)|ещё раз|еще раз|каждый раз|не вижу|ужасн|убог|"
    r"неправильн|криво|нейрослоп|каша|медленн|долго",
    re.I,
)
SCOPE_PLAN = re.compile(r"ничего (делать|разрабатывать) не надо|только (план|продумать|прописать)|не (надо|нужно) (ничего )?(делать|кодить|разрабатывать)", re.I)
STOP = re.compile(r"^\s*(стоп|остановись|хватит|закругляйся)\b|бегом останавливайся", re.I)


def advice(prompt: str) -> str:
    parts = []
    if STOP.search(prompt):
        parts.append("Владелец остановил работу: доведи текущий шаг до целостного состояния, зафиксируй статус в плане и остановись. Новых действий не начинай.")
    if SCOPE_PLAN.search(prompt):
        parts.append("Режим: только план/исследование. Код, конфиги и сервисы не меняй; результат — документ.")
    if COMPLAINT.search(prompt):
        parts.append(
            "Это замечание владельца о твоей работе. Ему не нужны признания — нужен исправленный результат. "
            "Не пиши «моя ошибка», «ты прав», «извини», «признаю» и не объясняй, как так вышло, если он не спросил. "
            "1) Молча найди причину: какое правило проекта/AGENTS.md или какую проверку пропустил. "
            "2) Исправь и проверь исходный сценарий (для UI — скриншоты mobile и desktop). "
            "3) Ответ начни с того, что исправлено и чем проверено; причину — одной строкой без оценок себя. "
            "4) Если у проекта есть AGENTS.md — добавь строку в его раздел «Частые ошибки» (skill lesson: что нельзя → как правильно → чем проверить); "
            "если похожая строка уже есть — это повтор, закрепи проверкой (скрипт/lint/чек-лист), а не новой фразой. "
            "Если владелец спрашивает «почему» — сначала коротко ответь на вопрос."
        )
    return " ".join(parts)


def main() -> int:
    if "--self-test" in sys.argv:
        assert "замечание" in advice("опять отступ сломан") and "Назови" not in advice("опять отступ сломан")
        assert "только план" in advice("НИЧЕГО ДЕЛАТЬ НЕ НАДО, только план")
        assert "остановил" in advice("стоп, остановись")
        assert advice("добавь кнопку оплаты") == ""
        print("ok")
        return 0
    try:
        data = json.load(sys.stdin)
    except Exception:
        return 0
    if os.environ.get("AGENT_KIT_HOOK_DEBUG"):
        with open(os.environ["AGENT_KIT_HOOK_DEBUG"], "a") as log:
            log.write(json.dumps({"hook": os.path.basename(__file__), "keys": sorted(data)}, ensure_ascii=False) + "\n")
    text = advice(str(data.get("prompt") or ""))
    if text:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "UserPromptSubmit", "additionalContext": text}}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
